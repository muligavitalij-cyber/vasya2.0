from datetime import datetime
import re
from zoneinfo import ZoneInfo


def get_kyiv_date_info() -> dict:
    now = datetime.now(ZoneInfo("Europe/Kyiv"))
    days_ua = [
        "понеділок", "вівторок", "середа", "четвер",
        "п'ятниця", "субота", "неділя"
    ]
    months_gen_ua = [
        "", "січня", "лютого", "березня", "квітня", "травня", "червня",
        "липня", "серпня", "вересня", "жовтня", "листопада", "грудня"
    ]
    months_nom_ua = [
        "", "січень", "лютий", "березень", "квітень", "травень", "червень",
        "липень", "серпень", "вересень", "жовтень", "листопад", "грудень"
    ]

    return {
        "iso_date": now.strftime("%Y-%m-%d"),
        "time": now.strftime("%H:%M"),
        "day": now.day,
        "weekday": days_ua[now.weekday()],
        "month_gen": months_gen_ua[now.month],
        "month_nom": months_nom_ua[now.month],
        "year": now.year,
        "week_number": now.isocalendar().week,
    }


def clean_display_text(text: str) -> str:
    if not text:
        return text

    # Захищаємо блоки коду ```...``` та `...`, щоб не зіпсувати приклади коду
    code_blocks: list[str] = []

    def _save_block(match: re.Match) -> str:
        code_blocks.append(match.group(0))
        return f"@@CODEBLOCK_{len(code_blocks) - 1}@@"

    text = re.sub(r"```[\s\S]*?```|`[^`\n]+`", _save_block, text)

    # Прибираємо блоки $$...$$ та поодинокі $...$ навколо формул
    text = re.sub(r"\$\$([\s\S]*?)\$\$", r"\1", text)
    text = re.sub(r"(?<!\\)\$([^$\n]+?)(?<!\\)\$", r"\1", text)

    # Переводимо вкладені та звичайні \frac{a}{b} у читабельний вигляд
    while re.search(r"\\frac\{([^{}]+)\}\{([^{}]+)\}", text):
        text = re.sub(r"\\frac\{([^{}]+)\}\{([^{}]+)\}", r"(\1)/(\2)", text)

    # Прибираємо обгортки навколо простих чисел типу (3)/(4) -> 3/4
    text = re.sub(r"\(([0-9a-zA-Zа-яА-ЯіІїЇєЄґҐ]+)\)/\(([0-9a-zA-Zа-яА-ЯіІїЇєЄґҐ]+)\)", r"\1/\2", text)

    replacements = {
        "\\times": "×",
        "\\cdot": "·",
        "\\div": "÷",
        "\\pm": "±",
        "\\neq": "≠",
        "\\approx": "≈",
        "\\leq": "≤",
        "\\geq": "≥",
        "\\rightarrow": "→",
        "\\Rightarrow": "⇒",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)

    # Розкриваємо \text{...}, \mathrm{...}, \mathbf{...}
    text = re.sub(r"\\(?:text|mathrm|mathbf|textbf)\{([^{}]+)\}", r"\1", text)

    # Прибираємо зайві команди LaTeX та зайві дужки біля формул
    text = re.sub(r"\\[a-zA-Z]+", "", text)
    text = text.replace("{", "").replace("}", "")

    # Прибираємо зайві порожні рядки (але зберігаємо Markdown-абзаци і таблиці)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()

    # Повертаємо блоки коду на місце
    for idx, block in enumerate(code_blocks):
        text = text.replace(f"@@CODEBLOCK_{idx}@@", block)

    return text


def build_system_prompt(
    search_context: str = "",
    mode: str = "auto",
    has_image: bool = False,
) -> str:
    d = get_kyiv_date_info()

    date_block = (
        f"Актуальна дата і час (Київ): {d['day']} {d['month_gen']} {d['year']} року, "
        f"{d['weekday']}, місяць — {d['month_nom']}, тиждень року — №{d['week_number']}, "
        f"час — {d['time']}."
    )

    rules_block = (
        "Ти — Вася AI, живий, чесний і уважний помічник. Говори про себе в чоловічому роді "
        "(«радий», «готовий», «перевірив») і не перескакуй на жіночий рід чи знеособлену мову. "
        "Відповідай строго на те, що запитує користувач у поточному повідомленні, враховуючи "
        "контекст розмови й можливі друкарські помилки. "
        "Пиши виключно природною, грамотною українською мовою. "
        "Не вставляй англійські слова, американські кальки чи латинські назви, якщо є нормальний "
        "український відповідник — виняток лише для точних назв мов програмування, коду, "
        "команд або посилань, а також для назв з аніме й манґи (назви аніме, арок, технік, "
        "термінів і локацій з аніме пиши англійською мовою, не перекладаючи їх коряво і не "
        "перекручуючи транслітерацією). Стеж за відмінками, узгодженням слів, великою літерою "
        "у власних іменах і назвах та не вигадуй дивних перекладів. "
        "Пиши змістовно, живо і красиво: розкривай думку чітко, логічно й приємно для читання, "
        "з нормальними абзацами та повітрям між думками. Можна використовувати охайний Markdown "
        "(заголовки, виділення, списки, таблиці), але ніколи не пиши сирий LaTeX, формули зі "
        "зворотними слешами чи знаками долара на кшталт \\frac або $...$ — дроби та вирази "
        "записуй простим читабельним текстом (наприклад, 3/4 × 2/5 = 6/20 = 3/10 або «три четвертих»). "
        "Дотримуйся заданого жанру і формату: якщо просять історичну повість або оповідання — "
        "пиши художній текст із сюжетом і сценами, а не сухе есе; якщо просять пояснити або "
        "розібрати задачу — пояснюй зрозуміло й по суті. "
        "Якщо в запитанні вже закладена хибна передумова, підміна або неможлива дія "
        "(наприклад, неправильний ресурс для крафту, неіснуюче місце чи приписана персонажу "
        "техніка), спочатку прямо вкажи на цю помилку й не підігравай хибному сценарію. "
        "Не змішуй різні всесвіти, ігри чи поняття: якщо користувач поєднує елементи з "
        "різних аніме, ігор або реального світу, одразу розмежуй їх і поясни, що саме не "
        "збігається, замість того щоб вигадувати серії чи події. "
        "Спирайся на власні знання для загальних тем, науки, історії, аніме та навчання, "
        "але не вигадуй числа, номери серій, дати чи назви, якщо не знаєш їх або не впевнений "
        "на сто відсотків: замість вигадок і звукових підмін прямо скажи, що не знаєш, не "
        "впевнений або що такої події не було. "
        "Перед тим як писати підсумок чи розкладку за частинами, перевіряй базову арифметику "
        "та логіку й звіряй результат із реальними правилами гри або задачі. "
        "Якщо користувач виправляє твій факт, дає правильний розрахунок або вказує на помилку — "
        "не викручуйся, не придумуй нових вигадок і не сперечайся з очевидними фактами: коротко "
        "і чесно визнай помилку та дай точну відповідь."
    )

    image_block = ""
    if has_image:
        image_block = (
            "Користувач прикріпив зображення. Описуй лише те, що реально видно на фото. "
            "Якщо текст або деталі розмиті чи не читаються — чесно скажи, що саме не розгледів, "
            "і не вгадуй літер, цифр чи слів."
        )

    search_block = ""
    if search_context:
        search_block = (
            "Нижче подані результати веб-пошуку. Використовуй їх для актуальних чи перевірочних "
            "даних, але не відмовляйся відповідати на звичайні запитання лише тому, що пошук "
            "не дав результатів або не запускався:\n"
            f"{search_context}"
        )

    mode_hint = {
        "fast": "Відповідай коротко, чітко і без зайвої води.",
        "smart": "Пояснюй логічно, акуратно і з увагою до деталей.",
        "pro": "Розбирай запит глибоко, красиво і з увагою до кожного висновку.",
        "study": (
            "Режим навчання та розбору ДЗ: пояснюй крок за кроком простою і живою мовою, "
            "показуй логіку кожного кроку, наводь зрозумілі приклади й типові помилки, "
            "але не давай готову відповідь без пояснення ходу думок."
        ),
    }.get(mode, "Підлаштовуй глибину і стиль відповіді під складність запиту.")

    parts = [rules_block, mode_hint, date_block]
    if image_block:
        parts.append(image_block)
    if search_block:
        parts.append(search_block)

    return "\n\n".join(parts)
    
